"""Regenerate docs/TOOLS.md from the live MCP tool registry (names, params, docstrings)."""
import asyncio, json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from otmcp.server import mcp

async def main():
    tools = await mcp.list_tools()
    out = ["# MCP tool reference", "", "_Generated by `scripts/gen_tool_docs.py` from the running server. Do not edit by hand._", ""]
    for t in tools:
        out.append(f"## `{t.name}`")
        out.append("")
        out.append((t.description or "").strip())
        props = (t.inputSchema or {}).get("properties", {})
        req = set((t.inputSchema or {}).get("required", []))
        if props:
            out += ["", "| param | type | required | default |", "|---|---|---|---|"]
            for k, v in props.items():
                typ = v.get("type") or "/".join(x.get("type", "?") for x in v.get("anyOf", [])) or "any"
                out.append(f"| `{k}` | {typ} | {'yes' if k in req else ''} | {json.dumps(v.get('default')) if 'default' in v else ''} |")
        out.append("")
    p = pathlib.Path(__file__).resolve().parents[1] / "docs" / "TOOLS.md"
    p.write_text("\n".join(out), encoding="utf-8")
    print(f"{len(tools)} tools -> {p}")

asyncio.run(main())
