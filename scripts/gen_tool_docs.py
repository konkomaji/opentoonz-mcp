"""Regenerate docs/TOOLS.md from the live MCP tool registry (names, parameters, docstrings).

usage: python scripts/gen_tool_docs.py [--check]
--check exits 1 when docs/TOOLS.md is out of date (used by CI).
"""
import asyncio
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from otmcp import __version__  # noqa: E402
from otmcp.server import mcp  # noqa: E402

OUT = ROOT / "docs" / "TOOLS.md"


async def render() -> str:
    tools = await mcp.list_tools()
    out = ["# Tool reference", "",
           f"_{len(tools)} tools in opentoonz-mcp {__version__}. Generated by `scripts/gen_tool_docs.py` "
           f"from the running server; do not edit by hand._", ""]
    for t in tools:
        out += [f"## `{t.name}`", "", (t.description or "").strip()]
        props = (t.inputSchema or {}).get("properties", {})
        req = set((t.inputSchema or {}).get("required", []))
        if props:
            out += ["", "| parameter | type | required | default |", "|---|---|---|---|"]
            for k, v in props.items():
                typ = v.get("type") or "/".join(x.get("type", "?") for x in v.get("anyOf", [])) or "any"
                default = json.dumps(v.get("default")) if "default" in v else ""
                out.append(f"| `{k}` | {typ} | {'yes' if k in req else ''} | {default} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    text = asyncio.run(render())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/TOOLS.md is out of date: run python scripts/gen_tool_docs.py")
            return 1
        print("docs/TOOLS.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
